package main

import "fmt"

const pi = 3.14

var radius float64 = 5

func main() {
	x := 2
	fmt.Printf("the value of x is %v and the type of x is %T\n", x, x)
	fmt.Printf("the value of pi is %v and the type of pi is %T\n", pi, pi)
	fmt.Printf("the value of radius is %v and the type of radius is %T\n", radius, radius)
}
